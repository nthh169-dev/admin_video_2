-- 1. Bảng users (Tương ứng users.db)
CREATE TABLE IF NOT EXISTS public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    password TEXT NOT NULL,
    security_answer TEXT NOT NULL DEFAULT 'vibe2026',
    role TEXT NOT NULL DEFAULT 'USER',
    avatar TEXT,
    created_at TEXT DEFAULT CURRENT_DATE::TEXT
);

-- 2. Bảng categories (Tương ứng video_categories.db)
CREATE TABLE IF NOT EXISTS public.categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    slug TEXT NOT NULL UNIQUE,
    color_badge TEXT DEFAULT '#2563EB',
    description TEXT
);

-- 3. Bảng videos (Tương ứng videos.db)
CREATE TABLE IF NOT EXISTS public.videos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    thumbnail TEXT NOT NULL,
    views BIGINT DEFAULT 0,
    file_size_mb DOUBLE PRECISION DEFAULT 0,
    duration TEXT DEFAULT '10:00',
    category_id BIGINT DEFAULT 1,
    status TEXT DEFAULT 'published',
    created_at TEXT DEFAULT CURRENT_DATE::TEXT
);

-- 4. Bảng daily_views (Tương ứng video_analytics.db)
CREATE TABLE IF NOT EXISTS public.daily_views (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    view_date TEXT NOT NULL UNIQUE,
    total_views BIGINT NOT NULL DEFAULT 0
);

-- 5. Bảng monthly_views (Tương ứng video_analytics.db)
CREATE TABLE IF NOT EXISTS public.monthly_views (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    view_month TEXT NOT NULL UNIQUE,
    month_label TEXT NOT NULL,
    total_views BIGINT NOT NULL DEFAULT 0
);

-- ============================================================================
-- CẤU HÌNH QUYỀN TRUY CẬP (RLS POLICIES CHO PUBLISHABLE KEY / ANON KEY)
-- ============================================================================
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.videos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.daily_views ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.monthly_views ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow public full access on users" ON public.users;
CREATE POLICY "Allow public full access on users" ON public.users FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow public full access on categories" ON public.categories;
CREATE POLICY "Allow public full access on categories" ON public.categories FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow public full access on videos" ON public.videos;
CREATE POLICY "Allow public full access on videos" ON public.videos FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow public full access on daily_views" ON public.daily_views;
CREATE POLICY "Allow public full access on daily_views" ON public.daily_views FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow public full access on monthly_views" ON public.monthly_views;
CREATE POLICY "Allow public full access on monthly_views" ON public.monthly_views FOR ALL USING (true) WITH CHECK (true);

